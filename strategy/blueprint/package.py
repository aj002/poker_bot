"""Build a self-contained blueprint bot bundle and audit it against the package limits (offline).

A bundle is ``<out>/bot.py`` plus copies of exactly the ``strategy`` modules and table
files the bot uses at decision time, found by playing a short in-process tournament in
a fresh interpreter and recording imported modules and loaded tables. The pack goes to
``strategy/tables/data/blueprint-<ruleset>.npz`` inside the bundle, where
:func:`strategy.blueprint.runtime.pack_path` finds it. A sandboxed worker then needs
nothing from the repository beyond the arena SDK it preloads.

The load-time warm-up observations (``strategy/blueprint/data``, re-recorded with
``--write-warm``) are copied too.

Checks: total size under :data:`SIZE_LIMIT`, no numba / llvmlite / solver modules in the
closure, and the bundle's ``bot.py`` loads and plays from a scratch directory.

    python -m strategy.blueprint.package --pack PACK --out artifacts/blueprint/bundle
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SIZE_LIMIT = 100 * 1024 * 1024
FORBIDDEN = ("numba", "llvmlite", "strategy.solve", "strategy.blueprint.kernels", "strategy.blueprint.train")
LEAVES = {"points": "blueprint", "chips": "blueprint_chips", "capped": "blueprint_capped", "none": "blueprint_noleaf"}

BOT_TEMPLATE = '''"""Blueprint bot bundle ({leaf} leaf), generated by strategy.blueprint.package.

Pack: {pack_name} (data sha256 {pack_sha}).
"""

from pathlib import Path

from strategy.blueprint.runtime import BlueprintBot

PACK = Path(__file__).resolve().parent / "strategy" / "tables" / "data" / "{pack_file}"


def make_bot():
    return BlueprintBot("{leaf}", pack=PACK)
'''

_PROBE = r'''
import json, os, sys
os.environ["BLUEPRINT_PACK"] = sys.argv[1]
from strategy.tables import store
loaded = set()
for name in ("load", "load_arrays", "stream_arrays"):
    orig = getattr(store, name)
    def wrap(n, *a, _orig=orig, _kind=name, **k):
        loaded.add((_kind, n))
        return _orig(n, *a, **k)
    setattr(store, name, wrap)
from arena.agents.worker import play_table
from arena.benchmark.runner import Entrant, TableRunner, schedule, table_info
from arena.domain.models import TournamentConfig
from arena.table.service import seeded_table
config = TournamentConfig(initial_player_count=4, hand_cap=60)
from pathlib import Path
entrants = [Entrant(f"e{i}", Path(sys.argv[2]), False) for i in range(4)]
runner = TableRunner(config, entrants, isolation="in_process")
for a in schedule(config, 4, 1, "package-probe")[:2]:
    agents = {}
    for seat, entrant in a.seats.items():
        agents[seat] = runner._agent(seat, entrant, table_info(config, a, seat, runner.budget_ns))
        agents[seat].start()
    try:
        play_table(seeded_table(config, a.seed, table_id=a.table_id), agents)
    finally:
        for agent in agents.values():
            agent.close()
mods = sorted(m for m, v in sys.modules.items() if (m == "strategy" or m.startswith("strategy."))
              and getattr(v, "__file__", None))
files = sorted({os.path.relpath(sys.modules[m].__file__, sys.argv[3]) for m in mods})
print(json.dumps({"modules": mods, "files": files, "tables": sorted(loaded),
                  "all_modules": sorted(m.split(".")[0] for m in sys.modules)}))
'''


def closure(pack: Path, leaf: str = "points") -> dict:
    """Modules, source files and tables the bot touches while playing (fresh interpreter)."""
    bot = REPO / "strategy" / "blueprint" / "bots" / f"{LEAVES[leaf]}.py"
    out = subprocess.run([sys.executable, "-c", _PROBE, str(pack), str(bot), str(REPO)], cwd=REPO,
                         capture_output=True, text=True)
    if out.returncode:
        raise RuntimeError(f"closure probe failed:\n{out.stderr[-3000:]}")
    return json.loads(out.stdout.strip().splitlines()[-1])


def _table_files(tables) -> list[str]:
    from strategy.tables import store

    out = []
    for kind, name in tables:
        p = store.table_path(name) if kind == "load" else store.array_path(name)
        out.append(str(p.relative_to(REPO)))
    return sorted(set(out))


def build(pack: Path, out: Path, *, leaf: str = "points", ruleset_id: str = "practice_nlhe") -> dict:
    from strategy.blueprint.policy import PolicyPack

    pk = PolicyPack(pack)
    info = closure(pack, leaf)
    bad = [m for m in info["modules"] if any(m == f or m.startswith(f + ".") for f in FORBIDDEN)]
    bad += [m for m in info["all_modules"] if m in ("numba", "llvmlite")]
    if bad:
        raise RuntimeError(f"deployed path imports offline modules: {sorted(set(bad))}")
    if out.exists():
        shutil.rmtree(out)
    files = [f for f in info["files"] if f.startswith("strategy/")]
    packages = {str(Path(*Path(f).parts[:k]) / "__init__.py") for f in files for k in range(1, len(Path(f).parts))}
    for rel in sorted(set(files) | {p for p in packages if (REPO / p).exists()}):
        if "__pycache__" in rel:
            continue
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REPO / rel, out / rel)
    warm = REPO / "strategy" / "blueprint" / "data"
    for f in sorted(warm.glob("*.json.gz")):
        rel = f.relative_to(REPO)
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(f, out / rel)
    tables = _table_files(info["tables"])
    for rel in tables:
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REPO / rel, out / rel)
    dest = out / "strategy" / "tables" / "data" / f"blueprint-{ruleset_id}.npz"
    shutil.copyfile(pack, dest)
    (out / "bot.py").write_text(BOT_TEMPLATE.format(leaf=leaf, pack_name=pack.name, pack_file=dest.name,
                                                    pack_sha=pk.provenance["data_sha256"][:16]))
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    if size > SIZE_LIMIT:
        raise RuntimeError(f"bundle is {size / 1e6:.1f} MB, over the {SIZE_LIMIT / 1e6:.0f} MB limit")
    h = hashlib.sha256()
    for p in sorted(out.rglob("*")):
        if p.is_file():
            h.update(str(p.relative_to(out)).encode())
            h.update(p.read_bytes())
    manifest = {"leaf": leaf, "ruleset_id": ruleset_id, "bytes": size, "files": len(list(out.rglob("*.py"))),
                "tables": tables, "pack": {"source": str(pack), "data_sha256": pk.provenance["data_sha256"],
                                           "rows": pk.provenance["rows"], "bytes": dest.stat().st_size},
                "bundle_sha256": h.hexdigest()}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    return manifest


WARM_COUNTS = {"preflop": 24, "flop": 8, "turn": 8, "river": 8}


def write_warm(ruleset_id: str = "practice_nlhe") -> Path:
    """Record the load-time warm-up observations from one seeded in-process tournament block."""
    import gzip

    from arena.domain.models import TournamentConfig
    from strategy.blueprint import runtime
    from strategy.value.rollouts import run_rollouts

    seen: dict[str, list[str]] = {k: [] for k in WARM_COUNTS}
    decide, recorded = runtime.BlueprintBot.decide, runtime.warm_observations

    def record(self, obs, state):
        seen[obs.street].append(obs.model_dump_json())
        return decide(self, obs, state)

    runtime.BlueprintBot.decide, runtime.warm_observations = record, lambda _r: []
    try:
        lineup = ["strategy/blueprint/bots/blueprint.py", "style:aggressive", "baseline:calling_station", "style:rock",
                  "style:station", "style:switcher", "style:weak_tight", "baseline:nlhe_heuristic"]
        run_rollouts(TournamentConfig(initial_player_count=8, hand_cap=200), lineup, blocks=1,
                     base_seed=f"blueprint-warm|{ruleset_id}", jobs=1)
    finally:
        runtime.BlueprintBot.decide, runtime.warm_observations = decide, recorded
    picked = []
    for street, n in WARM_COUNTS.items():
        obs = seen[street]
        picked += [obs[i * len(obs) // n] for i in range(min(n, len(obs)))]
    out = runtime.WARM_DIR / f"warm-{ruleset_id}.json.gz"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(gzip.compress(json.dumps(picked).encode(), mtime=0))
    return out


def smoke(bundle: Path) -> None:
    """Load the bundle with only the arena SDK preloaded (as sandbox workers do) and the repository hidden."""
    bundle = bundle.resolve()
    code = ("import sys, os\n"
            "import arena.agents.sdk\n"
            f"sys.path = [p for p in sys.path if os.path.abspath(p or '.') != {str(REPO)!r}]\n"
            f"sys.path.insert(0, {str(bundle)!r})\n"
            "import strategy.blueprint.runtime as r\n"
            f"assert r.__file__.startswith({str(bundle)!r}), r.__file__\n"
            "import bot\n"
            "p = bot.make_bot().policy('practice_nlhe')\n"
            f"assert str(p.pack.path).startswith({str(bundle.resolve())!r}), p.pack.path\n"
            "assert p.pack.nbytes() > 0\n"
            "assert 'numba' not in sys.modules\n")
    subprocess.run([sys.executable, "-c", code], cwd="/tmp", check=True)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Build and audit a blueprint bot bundle")
    ap.add_argument("--pack", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--leaf", choices=sorted(LEAVES), default="points")
    ap.add_argument("--write-warm", action="store_true", help="re-record strategy/blueprint/data/warm-*.json.gz")
    a = ap.parse_args(argv)
    if a.write_warm:
        print(write_warm())
        return
    if a.pack is None or a.out is None:
        ap.error("--pack and --out are required")
    manifest = build(a.pack, a.out, leaf=a.leaf)
    smoke(a.out)
    print(json.dumps(manifest, indent=1))


if __name__ == "__main__":
    main()
