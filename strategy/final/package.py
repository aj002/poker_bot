"""Build the competition bundle: deterministic, hashed, self-contained, under 100 MB, no numba.

The import closure and the tables the bot loads are recorded by playing short in-process
tournaments on every practice ruleset in a fresh interpreter (the NLHE teacher path and
the generic path). Exactly those ``strategy`` modules, the generic fallback's closure
(:data:`strategy.policy.package.FALLBACK_FILES`), the blueprint and exploit packs, the
push/fold and card tables and the blueprint's warm-up observations are copied next to a
generated ``bot.py``. ``--reveal DIR`` bundles a build-day variant for the generic path.

``MANIFEST.json`` lists every file's sha256 and ``bundle_sha256``, a hash of every path
and its bytes (``MANIFEST.json`` and ``__pycache__`` excluded); :func:`verify` recomputes
it. The bytes depend only on the commit and the inputs, never on the machine, the time or
the output path, so two builds of one commit give the same hash.

Checks: total size at most :data:`SIZE_LIMIT`, no numba / llvmlite / solver / trainer
modules in the closure, and the bundle loads and plays every ruleset from a scratch
directory with the repository hidden.

    python -m strategy.final.package --out artifacts/final/bundle
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from strategy.blueprint.package import FORBIDDEN, SIZE_LIMIT, _table_files
from strategy.policy.package import FALLBACK_FILES, reveal_files

REPO = Path(__file__).resolve().parents[2]
FORBIDDEN_HERE = (*FORBIDDEN, "strategy.exploit.kernels", "strategy.exploit.experts", "strategy.exploit.collect",
                  "strategy.final.distill", "strategy.final.holdout", "strategy.final.package",
                  "strategy.final.equivalence")
PROBE_RULESETS = ("practice_nlhe", "uncertainty_shortdeck", "uncertainty_plo4")
MANIFEST = "MANIFEST.json"

BOT_TEMPLATE = '''"""Competition bot bundle, generated by strategy.final.package. Do not edit.

NLHE: exploiting blueprint (blueprint pack data sha256 {pack_sha}; exploit pack {xpack_sha}).
Any other ruleset: strategy.policy.generic.GenericBot.
"""

from pathlib import Path

from {entry_module} import {entry_class}

DATA = Path(__file__).resolve().parent / "strategy" / "tables" / "data"


def make_bot():
    return {entry_class}(pack=DATA / "{pack_file}", exploit_pack=DATA / "{xpack_file}"{extra})
'''
PROBE_BOT = '''from {entry_module} import {entry_class}


def make_bot():
    return {entry_class}(overrides={overrides!r})
'''

_PROBE = r'''
import json, os, sys
os.environ["BLUEPRINT_PACK"], os.environ["EXPLOIT_PACK"] = sys.argv[1], sys.argv[2]
from strategy.tables import store
loaded = set()
for name in ("load", "load_arrays"):
    orig = getattr(store, name)
    def wrap(n, *a, _orig=orig, _kind=name, **k):
        loaded.add((_kind, n))
        return _orig(n, *a, **k)
    setattr(store, name, wrap)
from pathlib import Path
from arena.agents.worker import play_table
from arena.benchmark.runner import Entrant, TableRunner, schedule, table_info
from arena.domain.models import TournamentConfig
from arena.table.service import seeded_table
for ruleset in json.loads(sys.argv[5]):
    config = TournamentConfig(ruleset_id=ruleset, initial_player_count=4, hand_cap=60)
    entrants = [Entrant(f"e{i}", Path(sys.argv[3]), False) for i in range(4)]
    runner = TableRunner(config, entrants, isolation="in_process")
    for a in schedule(config, 4, 1, "final-package-probe")[:2]:
        agents = {}
        for seat, entrant in a.seats.items():
            agents[seat] = runner._agent(seat, entrant, table_info(config, a, seat, runner.budget_ns))
            agents[seat].start()
        try:
            play_table(seeded_table(config, a.seed, table_id=a.table_id), agents)
        finally:
            for agent in agents.values():
                agent.close()
mods = sorted(m for m, v in sys.modules.items() if (m == "strategy" or m.startswith("strategy."))
              and getattr(v, "__file__", None))
files = sorted({os.path.relpath(sys.modules[m].__file__, sys.argv[4]) for m in mods})
print(json.dumps({"modules": mods, "files": files, "tables": sorted(loaded),
                  "all_modules": sorted(m.split(".")[0] for m in sys.modules)}))
'''


def entry(overrides: dict | None) -> tuple[str, str]:
    """``(module, class)`` of the bundle's bot: the final bot, or the translating one when an
    override turns translation on (so the shipped bundle never contains translation code)."""
    if (overrides or {}).get("translate", "off") != "off":
        return "strategy.final.translated", "TranslatingFinalBot"
    return "strategy.final.runtime", "FinalBot"


def closure(pack: Path, xpack: Path, rulesets: tuple[str, ...] = PROBE_RULESETS,
            overrides: dict | None = None) -> dict:
    """Modules, source files and tables the bot touches while playing every ruleset (fresh interpreter)."""
    with tempfile.TemporaryDirectory() as tmp:
        bot = REPO / "strategy" / "final" / "bots" / "final.py"
        if overrides:
            module, cls = entry(overrides)
            bot = Path(tmp) / "bot.py"
            bot.write_text(PROBE_BOT.format(entry_module=module, entry_class=cls, overrides=overrides))
        return _probe(pack, xpack, rulesets, bot)


def _probe(pack: Path, xpack: Path, rulesets: tuple[str, ...], bot: Path) -> dict:
    out = subprocess.run([sys.executable, "-c", _PROBE, str(pack), str(xpack), str(bot), str(REPO),
                          json.dumps(list(rulesets))], cwd=REPO, capture_output=True, text=True,
                         env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
    if out.returncode:
        raise RuntimeError(f"closure probe failed:\n{out.stderr[-3000:]}")
    return json.loads(out.stdout.strip().splitlines()[-1])


def bundle_files(bundle: Path) -> list[Path]:
    """The hashed files: everything but the manifest and bytecode caches, in path order."""
    bundle = Path(bundle)
    return sorted((p for p in bundle.rglob("*") if p.is_file() and "__pycache__" not in p.parts
                   and p.relative_to(bundle).as_posix() != MANIFEST), key=lambda p: p.relative_to(bundle).as_posix())


def bundle_hash(bundle: Path) -> str:
    h = hashlib.sha256()
    for p in bundle_files(bundle):
        h.update(p.relative_to(bundle).as_posix().encode())
        h.update(b"\0")
        h.update(p.read_bytes())
        h.update(b"\0")
    return h.hexdigest()


def build(out: Path, *, pack: Path | None = None, xpack: Path | None = None, reveal: Path | None = None,
          ruleset_id: str = "practice_nlhe", overrides: dict | None = None) -> dict:
    """``overrides``: :class:`~strategy.exploit.runtime.ExploitBot` overrides baked into ``bot.py``
    (none by default, which leaves ``bot.py`` as it was); ``translate`` builds the bundle
    around :class:`~strategy.final.translated.TranslatingFinalBot` instead."""
    from strategy.blueprint.policy import PolicyPack
    from strategy.blueprint.runtime import pack_path
    from strategy.exploit.pack import ExploitPack
    from strategy.exploit.runtime import exploit_pack_path

    pack = Path(pack or pack_path(ruleset_id))
    xpack = Path(xpack or exploit_pack_path(ruleset_id))
    pk, xp = PolicyPack(pack), ExploitPack(xpack)
    info = closure(pack, xpack, overrides=overrides)
    module, cls = entry(overrides)
    bad = [m for m in info["modules"] if any(m == f or m.startswith(f + ".") for f in FORBIDDEN_HERE)]
    bad += [m for m in info["all_modules"] if m in ("numba", "llvmlite")]
    if bad:
        raise RuntimeError(f"deployed path imports offline modules: {sorted(set(bad))}")
    out = Path(out)
    tmp = out.with_name(out.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    files = {f for f in info["files"] if f.startswith("strategy/") and "__pycache__" not in f}
    files |= set(FALLBACK_FILES)
    files |= {str(Path(*Path(f).parts[:k]) / "__init__.py") for f in list(files) for k in range(1, len(Path(f).parts))
              if (REPO / Path(*Path(f).parts[:k]) / "__init__.py").exists()}
    files |= {str(f.relative_to(REPO)) for f in (REPO / "strategy" / "blueprint" / "data").glob("*.json.gz")}
    files |= set(_table_files(info["tables"]))
    copies = [(REPO / rel, rel) for rel in sorted(files)]
    data = "strategy/tables/data"
    pack_file, xpack_file = f"blueprint-{ruleset_id}.npz", f"exploit-{ruleset_id}.npz"
    copies = [c for c in copies if c[1] not in (f"{data}/{pack_file}", f"{data}/{xpack_file}")]
    copies += [(pack, f"{data}/{pack_file}"), (xpack, f"{data}/{xpack_file}")]
    if reveal is not None:
        copies += reveal_files(Path(reveal), tables=False)
    for src, rel in copies:
        dst = tmp / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    (tmp / "bot.py").write_text(BOT_TEMPLATE.format(pack_sha=pk.provenance["data_sha256"][:16],
                                                    xpack_sha=xp.provenance["data_sha256"][:16],
                                                    pack_file=pack_file, xpack_file=xpack_file,
                                                    entry_module=module, entry_class=cls,
                                                    extra=f", overrides={dict(sorted(overrides.items()))!r}"
                                                    if overrides else ""), encoding="ascii")
    hashed = bundle_files(tmp)
    size = sum(p.stat().st_size for p in hashed)
    if size > SIZE_LIMIT:
        shutil.rmtree(tmp)
        raise RuntimeError(f"bundle is {size / 1e6:.1f} MB, over the {SIZE_LIMIT / 1e6:.0f} MB limit")
    manifest = {
        "kind": "final", "entry": "bot.py:make_bot", "ruleset_id": ruleset_id,
        "teacher_rulesets": ["practice_nlhe"], "generic_rulesets": [r for r in PROBE_RULESETS if r != "practice_nlhe"]
        + (["reveal_variant"] if reveal is not None else []),
        "bytes": size, "py_files": sum(1 for p in hashed if p.suffix == ".py"),
        "pack": {"file": f"{data}/{pack_file}", "data_sha256": pk.provenance["data_sha256"]},
        "exploit_pack": {"file": f"{data}/{xpack_file}", "data_sha256": xp.provenance["data_sha256"],
                         "experts": xp.archetypes},
        "files": {p.relative_to(tmp).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in hashed},
        "bundle_sha256": bundle_hash(tmp),
    }
    if overrides:
        manifest["overrides"] = dict(sorted(overrides.items()))
    if reveal is not None:
        from strategy.rules.variants import VariantSpec

        spec = VariantSpec.from_dict(json.loads((Path(reveal) / "variant.json").read_text(encoding="utf-8")))
        manifest["reveal_variant_hash"] = spec.variant_hash()
    (tmp / MANIFEST).write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="ascii")
    if out.exists():
        shutil.rmtree(out)
    tmp.rename(out)
    return manifest


def verify(bundle: Path) -> dict:
    """Recompute the bundle hash and every file hash against ``MANIFEST.json``; raise on any difference."""
    bundle = Path(bundle)
    manifest = json.loads((bundle / MANIFEST).read_text(encoding="ascii"))
    files = {p.relative_to(bundle).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
             for p in bundle_files(bundle)}
    if files != manifest["files"]:
        diff = sorted(set(files.items()) ^ set(manifest["files"].items()))
        raise ValueError(f"{bundle}: files differ from the manifest: {[k for k, _ in diff][:10]}")
    if bundle_hash(bundle) != manifest["bundle_sha256"]:
        raise ValueError(f"{bundle}: bundle hash differs from the manifest")
    return manifest


def smoke(bundle: Path, rulesets: tuple[str, ...] = PROBE_RULESETS) -> None:
    """Load the bundle with only the arena preloaded and the repository hidden; every NLHE table and
    generic path resolves to the bundle's copies, and nothing imports numba."""
    bundle = Path(bundle).resolve()
    code = ("import sys, os\n"
            "import arena.agents.sdk\n"
            f"sys.path = [p for p in sys.path if os.path.abspath(p or '.') != {str(REPO)!r}]\n"
            f"sys.path.insert(0, {str(bundle)!r})\n"
            "import strategy.final.runtime as r\n"
            f"assert r.__file__.startswith({str(bundle)!r}), r.__file__\n"
            "import strategy.policy.generic as g\n"
            f"assert g.__file__.startswith({str(bundle)!r}), g.__file__\n"
            "import bot\n"
            "b = bot.make_bot()\n"
            f"assert str(b.teacher.xpack.path).startswith({str(bundle)!r}), b.teacher.xpack.path\n"
            f"assert str(b.teacher.policy('practice_nlhe').pack.path).startswith({str(bundle)!r})\n"
            "assert set(b.rulesets) >= {'practice_nlhe', 'uncertainty_shortdeck', 'uncertainty_plo4'}\n"
            "assert 'numba' not in sys.modules and 'llvmlite' not in sys.modules\n")
    subprocess.run([sys.executable, "-c", code], cwd="/tmp", check=True,
                   env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})


def _proc_kib(pid: int, field: str) -> int:
    with open(f"/proc/{pid}/status") as f:
        return next((int(line.split()[1]) for line in f if line.startswith(field + ":")), 0)


def _tree(pid: int) -> list[int]:
    """``pid`` and its descendants (the worker's interpreter runs under ``unshare --fork``)."""
    out, todo = [], [pid]
    while todo:
        p = todo.pop()
        out.append(p)
        for t in os.listdir(f"/proc/{p}/task"):
            with open(f"/proc/{p}/task/{t}/children") as f:
                todo += [int(c) for c in f.read().split()]
    return out


def worker_memory(bundle: Path, ruleset_id: str = "practice_nlhe", seed: str = "final-limits-v1") -> dict:
    """The deployed path's memory: one sandboxed worker process (interpreter, arena worker and the bot) plays
    a seeded 8-player table against in-process train-partition opponents; its peak and final RSS. The
    deadline is raised to 1 s: this measures memory, the deployed gate measures time."""
    from arena.agents.worker import WorkerPool, WorkerSeat, play_table
    from arena.domain.models import TournamentConfig
    from strategy.search.evaluate import _init, make_tasks, seat_agents
    from strategy.search.population import load_population

    config = TournamentConfig(ruleset_id=ruleset_id, initial_player_count=8, hand_cap=200)
    _init(config.model_dump_json())
    task = make_tasks(load_population(), "train", ruleset_id=ruleset_id, players=8, count=1, namespace=seed)[0]
    with WorkerPool(size=1) as pool:
        art = pool.stage(Path(bundle))
        agents, cs, table = seat_agents(config, task, lambda s, info: WorkerSeat(s, art, info, pool.acquire,
                                                                                 budget_ns=10**9))
        seat = agents[cs]
        try:
            play_table(table, agents)
            pids = _tree(seat.channel.proc.pid)
            peak = max(_proc_kib(p, "VmHWM") for p in pids) * 1024
            rss = max(_proc_kib(p, "VmRSS") for p in pids) * 1024
        finally:
            seat.close()
    return {"worker_peak_rss_bytes": peak, "worker_rss_bytes": rss, "decisions": seat.stats.decisions,
            "fallbacks": sum(seat.stats.fallbacks.values())}


def limits(bundle: Path, rulesets: tuple[str, ...] = ("practice_nlhe", "uncertainty_plo4")) -> dict:
    """Artifact bytes; per ruleset, the peak RSS of one sandboxed worker process playing the bundle (the
    deployed shape: one process per seat), which must stay at or under :data:`SIZE_LIMIT`; and, for
    information, the memory 8 instances add in one process (:func:`strategy.rehearsal.runner.probe_bundle`;
    each instance holds its own copy of the packs). numpy is expected, numba is not."""
    from arena.domain.models import TournamentConfig
    from strategy.rehearsal.runner import probe_bundle

    bundle = Path(bundle).resolve()
    size = sum(p.stat().st_size for p in bundle_files(bundle))
    out: dict = {"bytes": size, "size_ok": size <= SIZE_LIMIT, "rulesets": {}}
    for r in rulesets:
        p = probe_bundle(bundle, TournamentConfig(ruleset_id=r, initial_player_count=8, hand_cap=200))
        w = worker_memory(bundle, r)
        row = {"worker": w, "eight_in_process_bot_rss_bytes": p["bot_rss_bytes"],
               "loaded_from_bundle": p["loaded_from_bundle"],
               "heavy_modules": sorted({m.split(".")[0] for m in p["heavy_modules"]})}
        row["ok"] = (p["loaded_from_bundle"] and w["worker_peak_rss_bytes"] <= SIZE_LIMIT
                     and p["fallbacks"] == 0 and w["fallbacks"] == 0
                     and not set(row["heavy_modules"]) & {"numba", "llvmlite"})
        out["rulesets"][r] = row
    out["ok"] = out["size_ok"] and all(p["ok"] for p in out["rulesets"].values())
    return out


def submit(bundle: Path, dest: Path) -> dict:
    """``final-bot-<hash12>.tar.gz`` (sorted entries, zero mtimes and owners) and ``SHA256SUMS`` in ``dest``."""
    from strategy.rehearsal.runner import deterministic_tar

    m = verify(bundle)
    name = f"final-bot-{m['bundle_sha256'][:12]}"
    tar = Path(dest) / f"{name}.tar.gz"
    sha = deterministic_tar(Path(bundle), tar, name)
    (Path(dest) / "SHA256SUMS").write_text(f"{sha}  {tar.name}\n", encoding="ascii")
    return {"path": str(tar), "sha256": sha, "bytes": tar.stat().st_size, "bundle_sha256": m["bundle_sha256"]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Build, smoke-test and hash the competition bundle")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--pack", type=Path)
    ap.add_argument("--exploit-pack", type=Path)
    ap.add_argument("--reveal", type=Path, help="reveal directory (variant.json) for the generic path")
    ap.add_argument("--verify", action="store_true",
                    help="only check an existing bundle: hashes, smoke and the size / memory limits")
    ap.add_argument("--submit", type=Path, help="with --verify: write the tarball and SHA256SUMS to this directory")
    ap.add_argument("--override", action="append", default=[], metavar="KEY=VALUE",
                    help="ExploitBot override baked into bot.py, e.g. translate=postflop (repeatable)")
    a = ap.parse_args(argv)
    overrides = {}
    for item in a.override:
        k, sep, v = item.partition("=")
        if not sep:
            ap.error(f"--override {item!r} is not KEY=VALUE")
        try:
            overrides[k] = json.loads(v)
        except json.JSONDecodeError:
            overrides[k] = v
    if a.verify:
        m = verify(a.out)
        smoke(a.out)
        lim = limits(a.out)
        rep = {"bundle_sha256": m["bundle_sha256"], "limits": lim, "ok": lim["ok"]}
        if a.submit and lim["ok"]:
            rep["tarball"] = submit(a.out, a.submit)
        print(json.dumps(rep, indent=1))
        return 0 if lim["ok"] else 1
    manifest = build(a.out, pack=a.pack, xpack=a.exploit_pack, reveal=a.reveal, overrides=overrides or None)
    smoke(a.out)
    verify(a.out)
    print(json.dumps({k: v for k, v in manifest.items() if k != "files"}, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
