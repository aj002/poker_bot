"""A workload-matched control bot: check or call after burning a fixed CPU time per decision.

A calling station spends about 20 us per decision, so it meets far fewer host events
inside its decision windows than a bot that spends 300 us. The burner spends
``burn_ns`` of thread CPU time per decision (in a busy loop over a small buffer),
set to the candidate's median worker time, so a control table exposes the host for
about as long per decision as the candidate does. Its work is identical on every
decision: any timeout it suffers is the host's, which makes its timeouts, classified
by the same rules as the candidate's, the yardstick for the candidate's.

The bundle is self-contained (it imports only the SDK) and carries its burn time in
the source, so the artifact hash pins it.
"""

from __future__ import annotations

import statistics
from array import array
from collections.abc import Sequence
from pathlib import Path

from arena.benchmark.runner import Entrant, TableRunner, schedule
from arena.domain.models import TournamentConfig
from strategy.eval.policies import ResolvedPolicy, resolve_policy

BURNER_BASE_NS = 15_000
"""Sandboxed decide wall time of the burner beyond its burn (loop exit, action build)."""

BURN_TEMPLATE = '''"""Workload-matched control generated by strategy.eval.burn: {burn_ns} ns of CPU per decision."""

import time

from arena.agents.sdk import ExplicitStateBot, check_or_call

BURN_NS = {burn_ns}


class Burner(ExplicitStateBot):
    name = "cpu_burner"
    rulesets = ("practice_nlhe", "uncertainty_shortdeck", "uncertainty_plo4")

    def __init__(self):
        self.buf = bytearray(4096)

    def decide(self, observation, state):
        end = time.thread_time_ns() + BURN_NS
        buf, i = self.buf, 0
        while time.thread_time_ns() < end:
            buf[i & 4095] = (buf[i & 4095] + 1) & 255
            i += 1
        return check_or_call(observation.legal), state


def make_bot():
    return Burner()
'''


def burn_bundle(out_dir: Path, burn_ns: int) -> ResolvedPolicy:
    """Write (or reuse) a burner bundle in ``out_dir`` and resolve it as a policy."""
    if burn_ns < 0:
        raise ValueError("burn_ns must be non-negative")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "bot.py").write_text(BURN_TEMPLATE.format(burn_ns=int(burn_ns)), encoding="utf-8")
    return resolve_policy(str(out_dir))


def matched_burn_ns(decide_wall_ns: Sequence[int]) -> int | None:
    """Burn time whose sandboxed decide wall time matches the median of ``decide_wall_ns``."""
    if not decide_wall_ns:
        return None
    return max(0, int(statistics.median(decide_wall_ns)) - BURNER_BASE_NS)


def calibrate(config: TournamentConfig, entrants: Sequence[Entrant], *, seed: str, budget_ns: int | None = None,
              entrant: int = 0) -> list[int]:
    """Sandboxed decide wall times of ``entrant`` over one probe table (its own seed,
    ``<seed>|calibration``, so no counted table is replayed)."""
    runner = TableRunner(config, entrants, isolation="sandbox", budget_ns=budget_ns)
    try:
        result = runner.run(schedule(config, len(entrants), 1, f"{seed}|calibration")[0])
    finally:
        runner.close()
    return list(array("q", result.worker_wall_ns.get(entrant, b"")))


__all__ = ["BURNER_BASE_NS", "burn_bundle", "calibrate", "matched_burn_ns"]
