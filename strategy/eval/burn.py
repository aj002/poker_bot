"""A workload-matched control bot: check or call after a fixed amount of CPU work per decision.

A calling station spends about 20 us per decision, so it meets far fewer host events
inside its decision windows than a bot that spends 300 us. The burner runs a fixed
number of loop iterations over a small buffer per decision, calibrated so its
sandboxed median decide time equals the candidate's. The work is fixed, not the
time: a host stall (charged to the thread's CPU clock on this VM) and a host
slowdown (cold caches, a contended core) both stretch the burner's decide exactly
as they stretch the candidate's. Its work is identical on every decision, so any
timeout it suffers is the host's, which makes its timeouts, classified by the same
rules as the candidate's, the yardstick for the candidate's.

The bundle is self-contained (it imports only the SDK) and carries its iteration
count in the source, so the artifact hash pins it.
"""

from __future__ import annotations

import statistics
import tempfile
from array import array
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from arena.benchmark.runner import Entrant, TableRunner, schedule
from arena.domain.models import TournamentConfig
from strategy.eval.policies import ResolvedPolicy, resolve_policy

PROBE_ITERATIONS = 3_000
PROBE_SEATS = 6
PROBE_HAND_CAP = 40

BURN_TEMPLATE = '''"""Workload-matched control generated by strategy.eval.burn: {iterations} loop iterations per decision."""

from arena.agents.sdk import ExplicitStateBot, check_or_call

ITERATIONS = {iterations}


class Burner(ExplicitStateBot):
    name = "cpu_burner"
    rulesets = ("practice_nlhe", "uncertainty_shortdeck", "uncertainty_plo4")

    def __init__(self):
        self.buf = bytearray(4096)

    def decide(self, observation, state):
        buf = self.buf
        for i in range(ITERATIONS):
            buf[i & 4095] = (buf[i & 4095] + 1) & 255
        return check_or_call(observation.legal), state


def make_bot():
    return Burner()
'''


def burn_bundle(out_dir: Path, iterations: int) -> ResolvedPolicy:
    """Write (or reuse) a burner bundle in ``out_dir`` and resolve it as a policy."""
    if iterations < 0:
        raise ValueError("iterations must be non-negative")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "bot.py").write_text(BURN_TEMPLATE.format(iterations=int(iterations)), encoding="utf-8")
    return resolve_policy(str(out_dir))


def calibrate(config: TournamentConfig, entrants: Sequence[Entrant], *, seed: str, budget_ns: int | None = None,
              entrant: int = 0) -> list[int]:
    """Sandboxed decide wall times of ``entrant`` over one probe table (its own seed,
    ``<seed>|calibration``, so no counted table is replayed)."""
    runner = TableRunner(config, entrants, isolation="sandbox", budget_ns=budget_ns)
    try:
        result = runner.run(schedule(config, len(entrants), 1, f"{seed}|calibration")[0])
    finally:
        runner.close()
    return list(array("q", result.worker_wall_ns.get(entrant, b"")))


def _burner_median(ruleset_id: str, iterations: int, seed: str) -> float:
    config = TournamentConfig(ruleset_id=ruleset_id, initial_player_count=PROBE_SEATS, hand_cap=PROBE_HAND_CAP)
    with tempfile.TemporaryDirectory(prefix="burner-probe-") as tmp:
        policy = burn_bundle(Path(tmp) / "cpu_burner", iterations)
        walls = calibrate(config, [policy.entrant("sandbox")] * PROBE_SEATS, seed=f"{seed}|burner-{iterations}")
    return statistics.median(walls)


def matched_iterations(decide_wall_ns: Sequence[int], *, ruleset_id: str, seed: str) -> dict[str, Any] | None:
    """Iterations whose sandboxed median decide wall time matches the median of
    ``decide_wall_ns``, from two burner probe tables (0 and ``PROBE_ITERATIONS``
    iterations); None without samples."""
    if not decide_wall_ns:
        return None
    target = statistics.median(decide_wall_ns)
    base = _burner_median(ruleset_id, 0, seed)
    per_iteration = max(1e-3, (_burner_median(ruleset_id, PROBE_ITERATIONS, seed) - base) / PROBE_ITERATIONS)
    return {"iterations": max(0, round((target - base) / per_iteration)), "target_median_ns": int(target),
            "burner_base_ns": int(base), "ns_per_iteration": round(per_iteration, 3),
            "calibration_decisions": len(decide_wall_ns)}


__all__ = ["burn_bundle", "calibrate", "matched_iterations"]
