"""Export precomputed CFR+ tables as a compact Python module (`tables_data.py`)."""

from __future__ import annotations

import base64
import io
import zlib
from pathlib import Path

import numpy as np


def main() -> None:
    src = Path(__file__).resolve().parent / "tables.npz"
    data = dict(np.load(src))
    # Quantize probability tables (in [0, 1]) to uint8 (0..255) -> max quantization error < 0.002!
    # Keep grids as float32 and playability as float16.
    compact: dict[str, np.ndarray] = {}
    for k, arr in data.items():
        if k in ("eff_bb_grid", "bf_grid", "n_behind_grid", "raw_eq", "playability"):
            compact[k] = arr.astype(np.float32 if k != "n_behind_grid" else np.int32)
        else:
            compact[k] = np.clip(np.round(arr * 255.0), 0, 255).astype(np.uint8)

    buf = io.BytesIO()
    np.savez_compressed(buf, **compact)
    raw = buf.getvalue()
    b85 = base64.b85encode(raw).decode("ascii")

    lines = [
        '"""Embedded precomputed CFR+ equilibrium tables (auto-generated by precompute.py)."""',
        "",
        "from __future__ import annotations",
        "import base64",
        "import io",
        "import numpy as np",
        "",
        "_B85 = (",
    ]
    chunk = 100
    for i in range(0, len(b85), chunk):
        lines.append(f'    "{b85[i:i+chunk]}"')
    lines.extend([
        ")",
        "",
        "def load_embedded_tables() -> dict[str, np.ndarray]:",
        "    raw = base64.b85decode(_B85.encode('ascii'))",
        "    out: dict[str, np.ndarray] = {}",
        "    with np.load(io.BytesIO(raw)) as npz:",
        "        for k in npz.files:",
        "            arr = npz[k]",
        "            if arr.dtype == np.uint8:",
        "                out[k] = (arr.astype(np.float32) / 255.0)",
        "            else:",
        "                out[k] = arr",
        "    return out",
        "",
    ])
    out = Path(__file__).resolve().parent / "tables_data.py"
    out.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
